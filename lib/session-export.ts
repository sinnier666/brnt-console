// Client-safe session export helpers shared by the results dialog and the
// live sessions panel: cookie formatting, downloads and nftoken resolution.

import { parseCookieText, cookiePairsFromSource, type ParsedCookie } from "@/lib/cookies";
import { buildMagicLink } from "@/lib/magic-link";

export function hostOf(url: string): string {
  try {
    return new URL(url).host;
  } catch {
    return url.slice(0, 40);
  }
}

export function filePart(s: string): string {
  return (
    s
      .replace(/[^a-zA-Z0-9.-]/g, "_")
      .replace(/_+/g, "_")
      .slice(0, 60) || "site"
  );
}

export function downloadText(filename: string, content: string, type = "text/plain") {
  const blob = new Blob([content], { type });
  const r = document.createElement("a");
  r.href = URL.createObjectURL(blob);
  r.download = filename;
  r.click();
  URL.revokeObjectURL(r.href);
}

/** Netscape cookies.txt — the standard ".txt" cookie format every tool ingests. */
export function toNetscape(cs: ParsedCookie[], host: string): string {
  const out = [
    "# Netscape HTTP Cookie File",
    `# Generated by BRNT LoginProbe on ${new Date().toISOString()}`,
    "",
  ];
  for (const c of cs) {
    const raw = (c.domain || host || "").trim().replace(/^\./, "");
    if (!raw) {
      out.push(`# skipped ${c.name} (no domain known)`);
      continue;
    }
    const sub = (c.domain || "").startsWith(".");
    const dom = sub ? "." + raw : raw;
    const exp = Number(c.expirationDate) > 0 ? Math.floor(Number(c.expirationDate)) : 0;
    out.push(
      `${c.httpOnly ? "#HttpOnly_" : ""}${dom}\t${sub ? "TRUE" : "FALSE"}\t${c.path || "/"}\t${
        c.secure ? "TRUE" : "FALSE"
      }\t${exp}\t${c.name}\t${c.value}`
    );
  }
  return out.join("\n") + "\n";
}

export function toHeader(cs: ParsedCookie[]): string {
  return cs.map((c) => `${c.name}=${c.value}`).join("; ");
}

/** Accepts a header string OR a full Netscape export and returns the pairs. */
export function cookiesFromSource(src: string): ParsedCookie[] {
  return parseCookieText(cookiePairsFromSource(src)).cookies;
}

export function isNetflixHost(url: string): boolean {
  return /(^|\.)netflix\.com$/i.test(hostOf(url));
}

export interface Nftoken {
  link: string;
  kind: "native" | "magic";
  expires: number | null;
}

/**
 * Resolve an nftoken login link for a cookie set: Netflix cookies with a
 * NetflixId get a NATIVE token (any browser, no extension); everything else
 * (and any native failure) falls back to the BR1 magic link, which needs the
 * Cookie Bridge extension to open.
 */
export async function resolveNftoken(
  target: string,
  cookies: ParsedCookie[],
  accessKey: string
): Promise<{ ok: true; nft: Nftoken; note?: string } | { ok: false; error: string }> {
  if (isNetflixHost(target) && cookies.some((c) => c.name === "NetflixId")) {
    try {
      const res = await fetch("/api/nftoken", {
        method: "POST",
        headers: { "content-type": "application/json", "x-brnt-access": accessKey },
        body: JSON.stringify({ jar: cookies }),
      });
      const j = await res.json().catch(() => null);
      if (res.ok && j?.ok && j.link) {
        return {
          ok: true,
          nft: {
            link: String(j.link),
            kind: "native",
            expires: Number.isFinite(j.expires) ? Number(j.expires) : null,
          },
        };
      }
      const why = String(j?.message || j?.error || `HTTP ${res.status}`);
      const built = await buildMagicLink(target, cookies).catch(() => null);
      if (built) return { ok: true, nft: { link: built.link, kind: "magic", expires: null }, note: `native mint failed (${why})` };
      return { ok: false, error: why };
    } catch (e) {
      const why = e instanceof Error ? e.message : String(e);
      const built = await buildMagicLink(target, cookies).catch(() => null);
      if (built) return { ok: true, nft: { link: built.link, kind: "magic", expires: null }, note: `native mint failed (${why})` };
      return { ok: false, error: why };
    }
  }
  try {
    const built = await buildMagicLink(target, cookies);
    return { ok: true, nft: { link: built.link, kind: "magic", expires: null } };
  } catch (e) {
    return { ok: false, error: e instanceof Error ? e.message : String(e) };
  }
}

export function nftokenTxtFor(nft: Nftoken, target: string, username = ""): string {
  const host = hostOf(target);
  return [
    "BRNT LoginProbe — nftoken login link",
    `Site: ${host}`,
    `Target: ${target}`,
    username ? `Username: ${username}` : null,
    `Generated: ${new Date().toISOString()}`,
    `Type: ${
      nft.kind === "native"
        ? "native Netflix nftoken (works in ANY browser — no extension needed)"
        : "magic link BR1 (open it with the BRNT Cookie Bridge extension v1.2+)"
    }`,
    nft.expires
      ? `Token expires: ${new Date(nft.expires * 1000).toISOString()}`
      : "Token expires: unknown (dies with the server-side session)",
    "",
    "== nftoken link ==",
    nft.link,
    "",
    "Treat this link like a password — anyone who opens it gets the logged-in session.",
  ]
    .filter((l) => l !== null)
    .join("\n") + "\n";
}
